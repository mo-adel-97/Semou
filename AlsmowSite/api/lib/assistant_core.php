/** Turns the core FAQ into documents for ranking (special answers are resolved at answer time). */
function as_core_docs(): array
{
    $docs = [];
    foreach (as_core_faq() as $i => [$q, $variants, $answer]) {
        $docs[] = [
            'id' => "core$i", 'kind' => 'core', 'title' => $q, 'boost' => 1.15,
            'fields' => [[$q, 3.0], [str_replace('|', ' ', $variants), 2.6]],
            'answer' => $answer,
        ];
    }
    return $docs;
}

/** Program advice from the interest words in the question. */
function as_advice(array $tokens): string
{
    $site = as_site();
    $progs = as_programs();
    $interest = [
        'حاسب' => ['حاسب', 'كمبيوتر', 'كومبيوتر', 'تقنيه', 'برامج مكتبيه', 'اوفيس', 'وورد', 'اكسل'],
        'انجليز' => ['انجليزي', 'انجليزيه', 'لغه', 'لغات', 'english'],
        'مستشف' => ['صحي', 'صحه', 'مستشفي', 'مستشفيات', 'طبي'],
        'موارد' => ['موظفين', 'شؤون', 'hr', 'توظيف', 'موارد'],
        'بيانات' => ['بيانات', 'طباعه', 'كتابه', 'ادخال'],
        'اعمال' => ['اعمال', 'بيزنس', 'تجاره', 'مشروع', 'اداره'],
        'مكتب' => ['سكرتاريه', 'سكرتيره', 'مكتب', 'مكتبيه'],
    ];
    $have = array_flip($tokens);
    $hits = [];
    foreach ($interest as $titleKey => $words) {
        foreach ($words as $w) {
            $nw = as_norm($w);
            if (isset($have[$nw]) || isset($have[as_stem($nw)])) {
                foreach ($progs as $p) if (str_contains(as_norm($p['title']), $titleKey)) $hits[$p['id']] = $p;
                break;
            }
        }
    }
    if ($hits) {
        $lines = ['بناءً على اهتمامك، قد تناسبك هذه البرامج:'];
        foreach ($hits as $p) $lines[] = "- **{$p['title']}**" . ($p['summary'] ? ': ' . mb_substr(trim((string) $p['summary']), 0, 90) . '…' : '');
        $lines[] = 'اسألني عن أي منها لأعطيك تفاصيله.';
        return implode("\n", $lines);
    }
    return "يسعدني ترشيح برنامج لك 🌿 أخبرني بمجال اهتمامك، مثلًا:\n- الإدارة والأعمال\n- الموارد البشرية\n- إدارة المستشفيات\n- الحاسب الآلي\n- اللغة الإنجليزية\nأو اطّلع على كل البرامج: $site/programs";
}

/* ---------- typos: the closest known word (edit distance on letters, not bytes) ---------- */

function as_lev(string $a, string $b): int
{
    $x = preg_split('//u', $a, -1, PREG_SPLIT_NO_EMPTY) ?: [];
    $y = preg_split('//u', $b, -1, PREG_SPLIT_NO_EMPTY) ?: [];
    $n = count($x);
    $m = count($y);
    if (abs($n - $m) > 2) return 9;
    $prev = range(0, $m);
    for ($i = 1; $i <= $n; $i++) {
        $cur = [$i];
        for ($j = 1; $j <= $m; $j++) {
            $cur[$j] = min($prev[$j] + 1, $cur[$j - 1] + 1, $prev[$j - 1] + ($x[$i - 1] === $y[$j - 1] ? 0 : 1));
        }
        $prev = $cur;
    }
    return $prev[$m];
}

/** A known word within 1 typo (2 for long words), or null. */
function as_fuzzy(string $w, array $vocab): ?string
{
    $len = mb_strlen($w);
    if ($len < 6) return null; // short words: too many real neighbours («الفرق» vs «الفرع»)
    $limit = $len >= 9 ? 2 : 1;
    $best = null;
    $bestD = $limit + 1;
    foreach ($vocab as $v => $_) {
        $v = (string) $v;
        if (abs(mb_strlen($v) - $len) > $limit) continue;
        $d = as_lev($w, $v);
        if ($d < $bestD) { $bestD = $d; $best = $v; if ($d === 1 && $limit === 1) break; }
    }
    return $bestD <= $limit ? $best : null;
}

/* ---------- unanswered questions, for the dashboard ---------- */

const AS_LOG_KEY = 'assistant_unanswered';

function as_log_unanswered(string $question): void
{
    $q = trim(mb_substr($question, 0, 300));
    if (mb_strlen($q) < 3) return;
    $key = as_norm($q);
    try {
        DB::pdo()->beginTransaction();
        $row = DB::one('SELECT v FROM settings WHERE k = ? FOR UPDATE', [AS_LOG_KEY]);
        $log = $row ? (json_decode((string) $row['v'], true) ?: []) : [];
        $found = false;
        foreach ($log as &$e) {
            if (($e['k'] ?? '') === $key) { $e['n'] = (int) ($e['n'] ?? 1) + 1; $e['at'] = date('c'); $found = true; break; }
        }
        unset($e);
        if (!$found) $log[] = ['k' => $key, 'q' => $q, 'n' => 1, 'at' => date('c')];
        usort($log, fn($a, $b) => strcmp((string) $b['at'], (string) $a['at']));
        $log = array_slice($log, 0, 300);
        DB::run('INSERT INTO settings (k, v) VALUES (?, ?) ON DUPLICATE KEY UPDATE v = VALUES(v)', [AS_LOG_KEY, json_encode($log, JSON_UNESCAPED_UNICODE)]);
        DB::pdo()->commit();
    } catch (Throwable $e) {
        if (DB::pdo()->inTransaction()) DB::pdo()->rollBack();
        error_log('[alsmow-assistant] log: ' . $e->getMessage());
    }
}

function as_unanswered(): array
{
    $row = DB::one('SELECT v FROM settings WHERE k = ?', [AS_LOG_KEY]);
    return $row ? (json_decode((string) $row['v'], true) ?: []) : [];
}

function as_unanswered_remove(?string $key): void
{
    $log = $key === null ? [] : array_values(array_filter(as_unanswered(), fn($e) => ($e['k'] ?? '') !== $key));
    DB::run('INSERT INTO settings (k, v) VALUES (?, ?) ON DUPLICATE KEY UPDATE v = VALUES(v)', [AS_LOG_KEY, json_encode($log, JSON_UNESCAPED_UNICODE)]);
}
