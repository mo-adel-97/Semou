function as_fill(string $t): string
{
    $f = as_facts();
    $set = as_settings();
    $now = new DateTime('now', new DateTimeZone('Asia/Riyadh'));
    $days = ['الأحد', 'الاثنين', 'الثلاثاء', 'الأربعاء', 'الخميس', 'الجمعة', 'السبت'];
    return strtr($t, [
        '{name}' => $f['name'],
        '{name_bot}' => $set['name'],
        '{contact}' => as_contact_block(),
        '{contact_full}' => implode("\n", as_contact_lines()),
        '{now}' => 'الوقت الآن في السعودية: **' . $now->format('g:i') . ($now->format('A') === 'AM' ? ' صباحًا' : ' مساءً') . '**، يوم **' . $days[(int) $now->format('w')] . '** ' . $now->format('Y/m/d') . '.',
        '{hours_line}' => $f['hours'] ? "أوقات العمل: **{$f['hours']}**" . ($f['phone'] ? "\nللتأكد اتصل على: {$f['phone']}" : '') : 'أوقات العمل غير منشورة، تواصل معنا للتأكد:' . "\n" . as_contact_block(),
    ]);
}

/** @return array{answer:string, suggestions:string[], courtesy:?string, rest:string}|null */
function as_smalltalk(string $question): ?array
{
    $norm = as_norm($question);
    if ($norm === '') return null;
    foreach (as_smalltalk_rules() as $r) {
        // whole words only ("بوت" must not match inside another word)
        $re = '/(?<!\p{L})(?:' . $r['re'] . ')(?!\p{L})/u';
        if (!preg_match($re, $norm)) continue;
        $rest = trim(preg_replace('/\s+/u', ' ', preg_replace($re, ' ', $norm) ?? '') ?? '');
        return [
            'answer' => as_fill(as_pick($r['say'])),
            'suggestions' => ['ما البرامج المتاحة؟', 'كيف أسجل؟', 'أين مقركم وما أوقات العمل؟'],
            'courtesy' => isset($r['courtesy']) ? as_fill($r['courtesy']) : null,
            'rest' => $rest,
        ];
    }
    return null;
}

