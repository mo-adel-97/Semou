/* ============================================================
   Built-in knowledge of the assistant (no external AI):
   - small talk: greetings, "how are you", "who are you", "are you a bot", talk to a human, thanks, bye…
     answered naturally and with a few variations, then steered back to how it can help;
   - a core FAQ of 35+ topics a visitor of a training institute asks. Every answer is built from the
     institute's real data (contact, programs, stats, partners, accreditation, announcement…). When a fact is
     not published, the answer says so honestly and gives the way to ask — it never invents fees or dates.
   The dashboard's own Q&A always wins over these (see as_answer).
   ============================================================ */

function as_pick(array $options): string { return $options[array_rand($options)]; }

/** Data used by the core answers. */
function as_facts(): array
{
    static $f = null;
    if ($f !== null) return $f;
    $s = all_settings();
    $g = $s['general'] ?? [];
    $c = $s['contact'] ?? [];
    $site = as_site();
    $progs = as_programs();
    $acc = array_values(array_unique(array_filter(array_map(fn($p) => trim((string) $p['accreditation']), $progs))));
    $modes = array_values(array_unique(array_filter(array_map(fn($p) => $p['mode'] ? (PROGRAM_MODES[$p['mode']] ?? $p['mode']) : null, $progs))));
    $social = array_filter($s['social'] ?? []);
    $stats = array_values(array_filter((array) ($s['stats']['items'] ?? []), fn($x) => !empty($x['label']) && (int) ($x['value'] ?? 0) > 0));
    $q = fn(string $sql) => (function () use ($sql) { try { return DB::all($sql); } catch (Throwable) { return []; } })();
    return $f = [
        'name' => $g['site_name'] ?? 'معهد السمو للتدريب',
        'site' => $site,
        'phone' => $c['phone'] ?? null,
        'whatsapp' => !empty($c['whatsapp']) ? 'https://wa.me/' . preg_replace('/\D+/', '', (string) $c['whatsapp']) : null,
        'email' => $c['email'] ?? null,
        'address' => $c['address'] ?? null,
        'hours' => $c['hours'] ?? null,
        'map' => $c['map_url'] ?? null,
        'lms' => $g['lms_url'] ?? null,
        'announcement' => $g['announcement'] ?? null,
        'eyebrow' => $s['hero']['eyebrow'] ?? '',
        'acc' => $acc,
        'modes' => $modes,
        'social' => $social,
        'stats' => $stats,
        'partners' => array_column($q('SELECT name FROM partners WHERE is_published = 1 ORDER BY sort'), 'name'),
        'accreditations' => array_column($q('SELECT name FROM accreditations WHERE is_published = 1 ORDER BY sort'), 'name'),
        'agreements' => $q('SELECT title, partner FROM agreements WHERE is_published = 1 ORDER BY sort LIMIT 10'),
        'testimonials' => $q('SELECT name, role, text FROM testimonials WHERE is_published = 1 ORDER BY sort LIMIT 3'),
        'featured' => array_values(array_filter($progs, fn($p) => !empty($p['badge']))),
        'women' => str_contains(as_norm(($s['hero']['eyebrow'] ?? '') . ' ' . ($s['about']['summary'] ?? '')), as_norm('نسائي')),
    ];
}

